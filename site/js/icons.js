// Map marker image: transit-style bullet (rounded square in the category colour, white glyph).
// Returns ImageData at the given pixel ratio for map.addImage.
export function markerImage(iconName, color, { size = 30, ratio = 2, draft = false, ring = false } = {}) {
  const px = Math.round(size * ratio);
  const c = new OffscreenCanvas(px, px);
  const g = c.getContext('2d');
  const pad = 2 * ratio, r = 7 * ratio;
  const box = (x, y, w, h, rr) => { g.beginPath(); g.roundRect(x, y, w, h, rr); };
  box(pad, pad, px - 2 * pad, px - 2 * pad, r);
  g.fillStyle = '#ffffff';
  g.fill();
  box(pad + 1.5 * ratio, pad + 1.5 * ratio, px - 2 * pad - 3 * ratio, px - 2 * pad - 3 * ratio, r - 1.5 * ratio);
  g.fillStyle = color;
  g.globalAlpha = draft ? 0.72 : 1;
  g.fill();
  g.globalAlpha = 1;
  if (ring) { box(pad, pad, px - 2 * pad, px - 2 * pad, r); g.lineWidth = 2.5 * ratio; g.strokeStyle = '#121417'; g.stroke(); }
  const s = (px - 2 * pad) * 0.62 / 24;
  g.save();
  g.translate(px / 2 - 12 * s, px / 2 - 12 * s);
  g.scale(s, s);
  g.strokeStyle = '#ffffff';
  g.lineWidth = 2.3;
  g.lineCap = 'round';
  g.lineJoin = 'round';
  g.stroke(new Path2D(ICON[iconName] || ICON.pin));
  g.restore();
  return g.getImageData(0, 0, px, px);
}

// Entrance arrow: a bold chevron pointing "up" (north) that the map rotates by the entrance bearing.
export function arrowImage(fill, { ratio = 2, size = 26 } = {}) {
  const px = Math.round(size * ratio);
  const c = new OffscreenCanvas(px, px);
  const g = c.getContext('2d');
  const s = px / 26;
  g.scale(s, s);
  g.beginPath();
  g.moveTo(13, 2); g.lineTo(23, 22); g.lineTo(13, 17); g.lineTo(3, 22); g.closePath();
  g.fillStyle = fill; g.fill();
  g.lineWidth = 2; g.strokeStyle = '#ffffff'; g.lineJoin = 'round'; g.stroke();
  return g.getImageData(0, 0, px, px);
}
